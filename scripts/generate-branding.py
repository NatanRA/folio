#!/usr/bin/env python3
"""Generate native Folio logo assets from the approved vector master."""
from pathlib import Path
import json
import subprocess
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
MASTER = ROOT / 'docs/branding/folio-rounded-stack.svg'


def main():
    source = MASTER.read_text()
    tree = ET.fromstring(source)
    paths = [node.attrib['d'] for node in tree.iter('{http://www.w3.org/2000/svg}path')]
    assert len(paths) == 3 and tree.attrib['viewBox'] == '0 0 128 128'
    path_xml = '\n'.join(f'    <path android:fillColor="#58DCCB" android:pathData="{path}"/>' for path in paths)
    resources = ROOT / 'app/src/main/res'
    (resources / 'drawable/portal_logo.xml').write_text(
        '<!-- Generated by scripts/generate-branding.py. -->\n'
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        '    android:width="32dp" android:height="32dp" android:viewportWidth="128" android:viewportHeight="128">\n'
        + path_xml + '\n</vector>\n')
    (resources / 'drawable/ic_launcher_foreground.xml').write_text(
        '<!-- Generated by scripts/generate-branding.py. -->\n'
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        '    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">\n'
        '    <group android:scaleX="0.56" android:scaleY="0.56" android:translateX="18.16" android:translateY="18.16">\n'
        + path_xml + '\n    </group>\n</vector>\n')
    imageset = ROOT / 'ios/Resources/Assets.xcassets/FolioLogo.imageset'
    imageset.mkdir(parents=True, exist_ok=True)
    (imageset / 'logo.svg').write_text(source.replace('currentColor', '#000000'))
    (imageset / 'Contents.json').write_text(json.dumps({
        'images': [{'filename': 'logo.svg', 'idiom': 'universal'}],
        'info': {'author': 'xcode', 'version': 1},
        'properties': {'preserves-vector-representation': True, 'template-rendering-intent': 'template'}
    }, indent=2) + '\n')
    subprocess.run(['swift', str(ROOT / 'ios/render-icon.swift'),
                    str(ROOT / 'ios/Resources/Assets.xcassets/AppIcon.appiconset/icon.png')], check=True, cwd=ROOT)
    print('Generated Android and iOS branding from the approved rounded stack.')


if __name__ == '__main__':
    main()
